int DuelFont_Glyph(char c, DuelFontSeg *out, int cap) {
    unsigned i;
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c == ' ') return 0;
    for (i = 0; i < sizeof(kGlyphs) / sizeof(kGlyphs[0]); i++) {
        if (kGlyphs[i].c == c) {
            int n = kGlyphs[i].n;
            int k;
            if (n > cap) n = cap;
            for (k = 0; k < n; k++) {
                out[k].x0 = kGlyphs[i].s[k * 4 + 0];
                out[k].y0 = kGlyphs[i].s[k * 4 + 1];
                out[k].x1 = kGlyphs[i].s[k * 4 + 2];
                out[k].y1 = kGlyphs[i].s[k * 4 + 3];
            }
            return kGlyphs[i].n;
        }
    }
    return 0;
}

float DuelFont_TextW(const char *s) {
    int n = 0;
    if (!s) return 0.0f;
    while (*s++) n++;
    if (n == 0) return 0.0f;
    return (float)n * DUEL_FONT_ADV - 1.0f;
}
